def get_lang():
    """تحديد لغة العرض الحالية."""
    lang = request.cookies.get("lang") or session.get("lang")
    if lang in LANGUAGES:
        return lang
    best = None
    try:
        best = request.accept_languages.best_match(list(LANGUAGES))
    except Exception:
        pass
    return best if best in LANGUAGES else DEFAULT_LANG


def translate(lang, key, **kwargs):
    """ترجمة مفتاح بالنص الإنجليزي الشائع، مع دعم placeholders مثل {name}."""
    table = TRANSLATIONS.get(lang, {})
    text = table.get(key, key)
    if kwargs:
        try:
            text = text.format(**kwargs)
        except (KeyError, IndexError):
            pass
    return text


def make_t(lang):
    """دالة ترجمة مربوطه بنفس اللغة داخل القوالب."""
    def t(key, **kwargs):
        return translate(lang, key, **kwargs)
    return t